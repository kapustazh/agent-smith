from datetime import datetime

from pydantic import BaseModel, Field, field_validator
from pathlib import Path
from typing import Any, Optional

# Color constants
GREEN = "\033[92m"
BLUE = "\033[94m"
RED = "\033[91m"
RESET = "\033[0m"


class AgConfig(BaseModel):
    task_file: str = Field(min_length=1)
    output: str = Field(min_length=1, default="../cache/solution.json")
    model_name: str = Field(min_length=1)
    provider_url: str = Field(min_length=1)
    env_file: str = ""
    api_key_file: str = ""
    max_iterations: int = 10
    max_retries: int = 3
    debug: bool = False

    @field_validator("task_file", mode="before")
    @classmethod
    def fix_task_file(cls, value: Any) -> str:
        try:
            f_name = str(value)
        except (KeyError, TypeError, ValueError):
            print("Can't find task_file(json): ", value, "!")
            f_name = ""

        if (not f_name) or (not Path(f_name).exists()):
            print("Can't find task_file(json): ", value, "!")
            raise ValueError(f"Can't find task_file(json): \" {value} \"!")

        return f_name


class SandboxConfig(BaseModel):
    """Sandbox configuration for student solutions.
    Uses allowlist approach: only imports in authorized_imports are allowed.
    Everything else is blocked by default.
    """

    authorized_imports: list[str] = Field(default_factory=lambda: [
        "math", "math.*",
        "collections", "collections.*",
        "itertools", "re", "json",
        "typing", "typing.*",
        "functools", "operator",
        "heapq", "bisect", "copy",
        "string", "random",
        "datetime", "datetime.*",
        "array", "cmath",])
    allowed_directories: list[str] = Field(
        default_factory=lambda: ["/testbed", "/tmp/agent"])
    max_execution_time_seconds: int = Field(default=30, gt=0, strict=True)
    max_memory_mb: int = Field(default=512, gt=0, strict=True)
    max_output_chars: int = Field(default=9000, gt=0, strict=True)
    max_output_bytes: int = Field(default=8192, gt=0, strict=True)


class SandboxIntermediateResult(BaseModel):
    """Represents the intermediate result of a sandbox tool execution."""

    success: bool = Field(
        description="Whether the tool or function executed successfully")
    tool_name: str = Field(
        description="Name of the tool or function that was executed")
    sandbox_output: str = Field(
        description="Sandbox execution result (stdout/stderr/error message)")


